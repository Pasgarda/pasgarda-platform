export const initObject = (itemMap) => {
    return Object.keys(itemMap).reduce((acc, key) => {
        acc[key] = 0;
        return acc;
    }, {});
};

export const getCategoryTotal = (detailsObj) => {
    if (!detailsObj || typeof detailsObj !== 'object') return 0;
    return Object.values(detailsObj).reduce((sum, v) => sum + Number(v), 0);
};

