export const getVotingBonusInfo = (contingentId, contingents, scoresList, sortedByVotes) => {
    const contingent = contingents?.find(c => c.id === contingentId);
    if (!contingent) return { rank: 8, percentage: 0, calculatedBonus: 0 };

    const catVotesList = (sortedByVotes || []).filter(c => c.category_type === contingent.category_type);
    const index = catVotesList.findIndex(c => c.id === contingentId);
    const rank = index + 1;

    const bonuses = { 1: 0.01, 2: 0.008, 3: 0.006, 4: 0.004, 5: 0.003, 6: 0.002, 7: 0.001 };
    const hasVotes = (contingent.votes_count || 0) > 0;
    const percentage = hasVotes ? (bonuses[rank] || 0) : 0;

    const scoreObj = scoresList?.find(s => s.contingent_id === contingentId) || contingent.score;
    const pbbDantonSum = scoreObj ? (parseInt(scoreObj.pbb_score) + parseInt(scoreObj.danton_score)) : 0;
    const calculatedBonus = Math.round(pbbDantonSum * percentage);

    return { rank, percentage: percentage * 100, calculatedBonus };
};

export const migratePbbDetails = (details, pbbMovements) => {
    if (!details || typeof details !== 'object') return {};

    const pbbKeys = Object.keys(pbbItems);
    const usesUniqueKeys = pbbKeys.some(k => k in details);

    if (usesUniqueKeys) {
        const result = {};
        for (const [key, name] of Object.entries(pbbItems)) {
            if (key in details) {
                result[name] = details[key];
            }
        }
        return result;
    }

    return details;
};
